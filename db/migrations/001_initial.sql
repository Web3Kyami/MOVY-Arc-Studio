CREATE TABLE IF NOT EXISTS schema_migrations (
  version INTEGER PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chain_cursor (
  chain_id INTEGER PRIMARY KEY,
  last_processed_block BIGINT NOT NULL CHECK (last_processed_block >= 0),
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS enrollment_event_cursor (
  chain_id INTEGER PRIMARY KEY,
  last_processed_block BIGINT NOT NULL CHECK (last_processed_block >= 0),
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS enrollment_history_cursor (
  chain_id INTEGER PRIMARY KEY,
  last_processed_block BIGINT NOT NULL CHECK (last_processed_block >= 0),
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS enrollment_state_history (
  chain_id INTEGER NOT NULL,
  wallet TEXT NOT NULL,
  block_number BIGINT NOT NULL CHECK (block_number >= 0),
  log_index INTEGER NOT NULL CHECK (log_index >= 0),
  destination TEXT NOT NULL,
  max_roundup_6 TEXT NOT NULL CHECK (max_roundup_6 ~ '^[0-9]+$'),
  daily_cap_6 TEXT NOT NULL CHECK (daily_cap_6 ~ '^[0-9]+$'),
  config_epoch BIGINT NOT NULL CHECK (config_epoch >= 0),
  status TEXT NOT NULL CHECK (status IN ('active', 'paused', 'revoked')),
  PRIMARY KEY (chain_id, wallet, block_number, log_index)
);
CREATE INDEX IF NOT EXISTS idx_enrollment_state_history_position
  ON enrollment_state_history(chain_id, lower(wallet), block_number DESC, log_index DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_enrollment_state_history_wallet_nocase
  ON enrollment_state_history(chain_id, lower(wallet), block_number, log_index);

CREATE TABLE IF NOT EXISTS payment_history_replay (
  chain_id INTEGER PRIMARY KEY,
  next_block BIGINT NOT NULL,
  target_block BIGINT NOT NULL,
  completed BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS worker_locks (
  lock_name TEXT PRIMARY KEY,
  owner_token UUID NOT NULL,
  lease_expires_at BIGINT NOT NULL,
  fencing_token BIGINT NOT NULL CHECK (fencing_token > 0)
);

CREATE TABLE IF NOT EXISTS api_rate_limits (
  rate_key TEXT PRIMARY KEY,
  window_started_at BIGINT NOT NULL,
  request_count BIGINT NOT NULL CHECK (request_count >= 0)
);
CREATE INDEX IF NOT EXISTS idx_api_rate_limits_window ON api_rate_limits(window_started_at);

CREATE TABLE IF NOT EXISTS enrollments (
  chain_id INTEGER NOT NULL,
  wallet TEXT NOT NULL,
  destination TEXT NOT NULL,
  max_roundup_6 TEXT NOT NULL CHECK (max_roundup_6 ~ '^[0-9]+$'),
  daily_cap_6 TEXT NOT NULL CHECK (daily_cap_6 ~ '^[0-9]+$'),
  config_epoch BIGINT NOT NULL CHECK (config_epoch >= 0),
  status TEXT NOT NULL CHECK (status IN ('active', 'paused', 'revoked')),
  enrolled_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (chain_id, wallet)
);
CREATE INDEX IF NOT EXISTS idx_enrollments_status ON enrollments(chain_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_enrollments_wallet_nocase
  ON enrollments(chain_id, lower(wallet));

CREATE TABLE IF NOT EXISTS observed_payments (
  payment_key TEXT PRIMARY KEY,
  chain_id INTEGER NOT NULL,
  tx_hash TEXT NOT NULL,
  log_index INTEGER NOT NULL CHECK (log_index >= 0),
  block_number BIGINT NOT NULL CHECK (block_number >= 0),
  payer TEXT NOT NULL,
  recipient TEXT NOT NULL,
  amount_6 TEXT NOT NULL CHECK (amount_6 ~ '^[0-9]+$'),
  roundup_6 TEXT NOT NULL CHECK (roundup_6 ~ '^[0-9]+$'),
  is_eligible BOOLEAN NOT NULL,
  exclusion_reason TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payments_payer ON observed_payments(chain_id, lower(payer));
CREATE INDEX IF NOT EXISTS idx_payments_block ON observed_payments(chain_id, block_number, log_index);

CREATE TABLE IF NOT EXISTS roundup_jobs (
  job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_key TEXT NOT NULL UNIQUE REFERENCES observed_payments(payment_key) ON DELETE RESTRICT,
  chain_id INTEGER NOT NULL,
  wallet TEXT NOT NULL,
  destination TEXT NOT NULL,
  roundup_amount_6 TEXT NOT NULL CHECK (roundup_amount_6 ~ '^[0-9]+$'),
  config_epoch BIGINT NOT NULL CHECK (config_epoch >= 0),
  status TEXT NOT NULL CHECK (status IN ('pending', 'submitting', 'submitted', 'confirmed', 'skipped', 'failed')),
  skip_reason TEXT,
  relayer_tx_hash TEXT,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  last_error TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_jobs_wallet ON roundup_jobs(chain_id, lower(wallet));
CREATE INDEX IF NOT EXISTS idx_jobs_status ON roundup_jobs(chain_id, status, job_id);
